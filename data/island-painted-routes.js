export const ISLAND_ROUTES=trails.map(line=>line.map(mapPoint));

// Index the tapered strips once. Both fingertip pathfinding and joystick
// movement ask the same question about the character's feet.
const tile=48, columns=Math.ceil(1536/tile), ground=new Map();
for(const line of trails)for(let i=1;i<line.length;i++){
 const [x,y,r]=line[i-1], [ex,ey,er]=line[i], dx=ex-x, dy=ey-y;
 const segment={x,y,r,dx,dy,dr:er-r,lengthSquared:dx*dx+dy*dy};
 const reach=Math.max(r,er);
 for(let row=Math.floor((Math.min(y,ey)-reach)/tile);row<=Math.floor((Math.max(y,ey)+reach)/tile);row++){
  for(let col=Math.floor((Math.min(x,ex)-reach)/tile);col<=Math.floor((Math.max(x,ex)+reach)/tile);col++){
   const key=row*columns+col;
   if(!ground.has(key))ground.set(key,[]);
   ground.get(key).push(segment);
  }
 }
}
export function paintedGround(worldX,worldY){
 const x=worldX/islandMapScale,y=worldY/islandMapScale,segments=ground.get(Math.floor(y/tile)*columns+Math.floor(x/tile));
 return segments?.some(s=>{
  const u=x-s.x,v=y-s.y,t=Math.max(0,Math.min(1,(u*s.dx+v*s.dy)/s.lengthSquared));
  return (u-t*s.dx)**2+(v-t*s.dy)**2<=(s.r+t*s.dr)**2;
 })??false;
}
