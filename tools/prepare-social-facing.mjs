import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
const require=createRequire(import.meta.url);
let sharp;try{sharp=require('sharp');}catch{sharp=require('../../cloudflare-tools/node_modules/sharp');}
const records=JSON.parse(await fs.readFile('docs/social-motions/facing-prompts.json','utf8')).records;
const names=['雛菊日常服','胡蘿蔔園丁裝','草莓烘焙裝','白色婚紗','橘子狐原裝','森林郵差裝','星空旅人裝','黑色西裝','蜂蜜熊原裝','蜂蜜烘焙裝','果園吊帶裝','蜂蜜紳士裝'];
const bases=JSON.parse(await fs.readFile('docs/social-motions/facing-base-catalog.json','utf8'));
const catalog=[...bases],report=[];
await fs.mkdir('assets/social-motions/v2',{recursive:true});
for(const [index,record]of records.entries()){
 const base=bases.find(o=>o.id===record.id);
 await fs.mkdir('output/social-motions/facing',{recursive:true});
 const path='output/social-motions/facing/'+record.id+'-source.png';
 await fs.copyFile(record.source,path);
 const {data,info}=await sharp(path).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const {width:w,height:h}=info,seen=new Uint8Array(w*h),queue=new Int32Array(w*h),parts=[];
 // Connected alpha components keep generated row spacing from cutting off ears.
 for(let start=0;start<w*h;start++){
  if(seen[start]||data[start*4+3]<48)continue;
  let head=0,tail=1,left=w,right=0,top=h,bottom=0;queue[0]=start;seen[start]=1;
  while(head<tail){const p=queue[head++],x=p%w,y=Math.floor(p/w);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
   for(const n of [x>0?p-1:-1,x<w-1?p+1:-1,y>0?p-w:-1,y<h-1?p+w:-1])if(n>=0&&!seen[n]&&data[n*4+3]>=48){seen[n]=1;queue[tail++]=n;}
  }
  if(tail>1200)parts.push({left,top,width:right-left+1,height:bottom-top+1,pixels:tail});
 }
 const sprites=parts.sort((a,b)=>b.pixels-a.pixels).slice(0,9).sort((a,b)=>a.top+a.height/2-b.top-b.height/2);
 if(sprites.length!==9)throw Error(record.id+': expected 9 separate poses, found '+sprites.length);
 const ordered=[];for(let row=0;row<3;row++)ordered.push(...sprites.slice(row*3,row*3+3).sort((a,b)=>a.left-b.left));
 // Center on the head rather than the tail or extended paw.
 for(const b of ordered){let sum=0,n=0;for(let y=b.top;y<b.top+b.height*.38;y++)for(let x=b.left;x<b.left+b.width;x++)if(data[(y*w+x)*4+3]>180){sum+=x-b.left;n++;}b.anchor=n?sum/n:b.width/2;}
 const extent=Math.max(...ordered.flatMap(b=>[b.anchor/b.height,(b.width-b.anchor)/b.height]));
 const bodyHeight=Math.min(304,Math.floor(134/extent)),cw=288,ch=336,baseline=322,composites=[];
 for(const [i,b]of ordered.entries()){
  const scale=bodyHeight/b.height,ww=Math.round(b.width*scale);
  const input=await sharp(path).extract({left:b.left,top:b.top,width:b.width,height:b.height}).resize(ww,bodyHeight).png().toBuffer();
  const row=Math.floor(i/3);composites.push({input,left:i%3*cw+Math.round(cw/2-b.anchor*scale),top:(row===2?3:row)*ch+baseline-bodyHeight});
 }
 for(let col=0;col<3;col++){
  const scale=bodyHeight/base.bodyHeight,ww=Math.round(base.cellWidth*scale),hh=Math.round(base.cellHeight*scale);
  const input=await sharp(base.image).extract({left:col*base.cellWidth,top:2*base.cellHeight,width:base.cellWidth,height:base.cellHeight}).resize(ww,hh).png().toBuffer();
  composites.push({input,left:col*cw+Math.round((cw-ww)/2),top:2*ch+Math.round(baseline-base.baseline*scale)});
 }
 const buf=await sharp({create:{width:cw*3,height:ch*4,channels:4,background:'#00000000'}}).composite(composites).webp({quality:82,alphaQuality:100,effort:6}).toBuffer();
 const hash=createHash('sha256').update(buf).digest('hex').slice(0,12),file='assets/social-motions/v2/'+record.id+'.'+hash+'.webp';
 await fs.writeFile(file,buf);
 catalog[catalog.findIndex(o=>o.id===record.id)]={...base,image:file,cellWidth:cw,cellHeight:ch,bodyHeight,baseline,facing:'right'};
 report.push({id:record.id,bytes:buf.length,sourceDimensions:[w,h],poses:ordered,bodyHeight});
 console.log(record.id,buf.length+' bytes',bodyHeight);
}
await fs.writeFile('data/social-motions.js','// Generated by tools/prepare-social-facing.mjs; immutable, lazy-loaded atlases.\nexport const SOCIAL_OUTFITS = '+JSON.stringify(catalog,null,2)+';\n');
await fs.writeFile('docs/social-motions/facing-asset-report.json',JSON.stringify({totalBytes:report.reduce((s,r)=>s+r.bytes,0),outfits:report},null,2)+'\n');
