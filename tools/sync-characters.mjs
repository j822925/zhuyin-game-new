// Mechanical catalog generation: the JSON is the only editable character list.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
export function validateCatalog(rows,{checkAssets=true}={}){
 if(!Array.isArray(rows)||rows.length<2)throw new Error('角色表至少需要兩個角色。');
 const ids=new Set();
 for(const c of rows){
  if(!/^[a-z][a-z0-9-]*$/.test(c.id)||ids.has(c.id))throw new Error('角色編號重複或格式不正確：'+c.id);ids.add(c.id);
  if(typeof c.name!=='string'||!c.name.trim()||!['animal','fairy','hero'].includes(c.category))throw new Error('角色名稱或分類不正確：'+c.id);
  if(!/^assets\/characters\/[a-zA-Z0-9_/-]+\.(png|webp)$/.test(c.image)||c.image.includes('..'))throw new Error('角色圖片路徑不正確：'+c.id);
  if(checkAssets&&!existsSync(path.join(root,c.image)))throw new Error('缺少圖片：'+c.image);
  if(typeof c.enabled!=='boolean'||typeof c.starter!=='boolean')throw new Error('enabled / starter 必須為布林值：'+c.id);
 }
 if(rows.filter(c=>c.starter).length<2)throw new Error('請保留至少兩個起始角色，供雙人選角。');
 return rows;
}
export function renderCatalog(rows){
 const server=rows.map(({id,category,starter,enabled})=>({id,category,starter,enabled}));
 return {browser:'// Generated by tools/sync-characters.mjs; edit data/characters.json.\nexport const CHARACTER_CATALOG = '+JSON.stringify(rows,null,2)+';\n',backend:'// BEGIN GENERATED CHARACTER CATALOG\nconst CHARACTER_CATALOG_ = '+JSON.stringify(server)+';\nfunction allCharacters_(){return CHARACTER_CATALOG_.map(c=>c.id);}\nfunction starterCharacters_(){return CHARACTER_CATALOG_.filter(c=>c.starter).map(c=>c.id);}\nfunction characterPool_(category){return CHARACTER_CATALOG_.filter(c=>c.category===category&&c.enabled).map(c=>c.id);}\n// END GENERATED CHARACTER CATALOG'};
}
function main(){
 const rows=validateCatalog(JSON.parse(readFileSync(path.join(root,'data/characters.json'),'utf8'))),out=renderCatalog(rows);
 const backendPath=path.join(root,'backend/game-api.gs'),source=readFileSync(backendPath,'utf8');
 const marker=/\/\/ BEGIN GENERATED CHARACTER CATALOG[\s\S]*?\/\/ END GENERATED CHARACTER CATALOG/;
 if(!marker.test(source))throw new Error('後台缺少同步區塊；未修改任何檔案。');
 const backend=source.replace(marker,out.backend),browserPath=path.join(root,'data/character-catalog.js');
 if(process.argv.includes('--check')){if(!existsSync(browserPath)||readFileSync(browserPath,'utf8')!==out.browser||source!==backend)throw new Error('角色表尚未同步。請執行 node tools/sync-characters.mjs');}
 else{writeFileSync(browserPath,out.browser);writeFileSync(backendPath,backend);}
 console.log('已驗證 '+rows.length+' 個角色；前端、轉蛋角色池與後台使用相同編號。');
}
if(process.argv[1]&&pathToFileURL(path.resolve(process.argv[1])).href===import.meta.url)main();
